export function getCatalog() {
  const stored = localStorage.getItem("luxore_catalog");
  if (!stored) {
    localStorage.setItem("luxore_catalog", JSON.stringify(DefaultCatalog));
    return DefaultCatalog;
  }
  try {
    const parsed = JSON.parse(stored);
    // اگر لوکل اسٹوریج میں ڈیٹا کم ہو یا پرانا ہو تو ڈیفالٹ ڈیٹا کے ساتھ مرج کریں
    if (!Array.isArray(parsed) || parsed.length < 5) {
      localStorage.setItem("luxore_catalog", JSON.stringify(DefaultCatalog));
      return DefaultCatalog;
    }
    return parsed;
  } catch (e) {
    localStorage.setItem("luxore_catalog", JSON.stringify(DefaultCatalog));
    return DefaultCatalog;
  }
}

export function saveCatalog(items) {
  localStorage.setItem("luxore_catalog", JSON.stringify(items));
}

export function addProduct(newWatch) {
  const current = getCatalog();
  current.push(newWatch);
  saveCatalog(current);
}

export function deleteProduct(id) {
  const current = getCatalog().filter((item) => item.id !== id);
  saveCatalog(current);
}
